function publishCandidate(raw: unknown): ValidatedDocument {
  const decoded = decodeDocumentShape(raw);
  if (!decoded.ok) throw new Error("OWNER_TEST_CANDIDATE_STRUCTURAL");
  const validated = validateDocumentSemantics(decoded.value);
  if (!validated.ok) throw new Error("OWNER_TEST_CANDIDATE_SEMANTIC");
  return validated.value;
}

type HarnessOptions = Readonly<{
  disposition?: "retained" | "explicitly-unavailable";
  estimate?: number;
  /**
   * The estimate the DISCLOSED impact was computed from, when it must stay
   * well-formed while the injected estimator misbehaves (REP-020 family).
   */
  disclosedEstimate?: number;
  transportGeneration?: number;
  nextSequence?: number;
  revision?: number;
  /** Skip the pending request + retiring transition (idle workflow). */
  idleTransition?: boolean;
}>;

type Harness = Readonly<{
  composition: StudioComposition;
  state: AppState;
  dependencies: ApplicationCommandDependencies;
  candidate: ValidatedDocument;
  request: PrepareImportReplacementPublicationRequest;
  acknowledgement: ImportNonUndoableConfirmationAcknowledgement | null;
  notifications: () => number;
  diagnostics: readonly StudioInterchangeOwnerDiagnostic[];
}>;

function createHarness(options: HarnessOptions = {}): Harness {
  const bootstrap = createStudioBootstrap();
  expect(bootstrap.ok).toBe(true);
  if (!bootstrap.ok) throw new Error("OWNER_TEST_BOOTSTRAP");
  const disposition = options.disposition ?? "retained";
  const estimate =
    options.estimate ??
    (disposition === "retained" ? STUB_ESTIMATE : OVERSIZED_ESTIMATE);
  const dependencies: ApplicationCommandDependencies = Object.freeze({
    ...bootstrap.value.dependencies,
    estimateHistoryRetainedBytes: () => estimate,
  });
  const candidate = publishCandidate(CANDIDATE_RAW);
  const revision = options.revision ?? bootstrap.value.state.revision;
  const base = bootstrap.value.state;
  const pending: PendingApplicationRequest = Object.freeze({
    kind: "document-transition",
    id: REQUEST_ID,
    documentId: base.document.id,
    baseRevision: revision,
    status: "running",
  });
  const transition = Object.freeze({
    kind: "retiring-transport",
    requestId: REQUEST_ID,
    origin: "canonical-import",
    baseRevision: revision,
    candidateDocumentId: candidate.id,
    undoDisposition: disposition,
  } as const);
  const state: AppState = Object.freeze({
    ...base,
    revision,
    ...(options.idleTransition === true
      ? {}
      : {
          pendingRequests: Object.freeze([pending]),
          documentTransition: transition,
        }),
    ...(options.transportGeneration === undefined
      ? {}
      : {
          transport: Object.freeze({
            ...base.transport,
            generation: options.transportGeneration,
          }),
        }),
    ...(options.nextSequence === undefined
      ? {}
      : { nextSequence: options.nextSequence }),
  });
  const diagnostics: StudioInterchangeOwnerDiagnostic[] = [];
  const composition = createStudioCompositionOverState(state, dependencies, {
    interchangeDiagnostics: (diagnostic) => diagnostics.push(diagnostic),
  });
  let notificationCount = 0;
  composition.controller.subscribe(() => {
    notificationCount += 1;
  });
  const disclosedEstimate = options.disclosedEstimate ?? estimate;
  const retainedImpact = Object.freeze({
    historyEntryRetainedBytes: disclosedEstimate,
    evictedUndoEntries: 0,
    redoEntriesCleared: 0,
    confirmationRequired: true,
    undoDisposition: "retained",
    undoEntriesAfterCommit: 1,
    undoRetainedBytesAfterCommit: disclosedEstimate,
    exportRecommended: false,
  } as const);
  const unavailableImpact = Object.freeze({
    historyEntryRetainedBytes: disclosedEstimate,
    evictedUndoEntries: 0,
    redoEntriesCleared: 0,
    confirmationRequired: true,
    undoDisposition: "explicitly-unavailable",
    undoEntriesAfterCommit: 0,
    undoRetainedBytesAfterCommit: 0,
    exportRecommended: true,
  } as const);
  const seed = Object.freeze({
    id: "owner-test-replace-1",
    label: "Import owner bridge candidate",
    logicalTimeMs: 5_000,
  });
  const identity = Object.freeze({
    requestId: REQUEST_ID,
    documentId: base.document.id,
    baseRevision: revision,
  });
  const acknowledgement: ImportNonUndoableConfirmationAcknowledgement | null =
    disposition === "explicitly-unavailable"
      ? Object.freeze({
          kind: "acknowledged",
          requirement: Object.freeze({
            schema: "changes.import-nonundoable-confirmation.v1",
            confirmationId: "owner-test-confirm-1",
            identity,
            candidateDocumentId: candidate.id,
            commandId: seed.id,
            disclosedImpact: unavailableImpact,
          }),
        } as const)
      : null;
  const request: PrepareImportReplacementPublicationRequest =
    disposition === "retained"
      ? Object.freeze({
          identity,
          sourceFormat: "canonical-json-v2",
          replacementOrigin: "canonical-import",
          candidate,
          replacementCommandSeed: seed,
          disclosedImpact: retainedImpact,
          currentTransition: transition as typeof transition & {
            undoDisposition: "retained";
          },
          nonUndoableConfirmation: null,
        } as const)
      : Object.freeze({
          identity,
          sourceFormat: "canonical-json-v2",
          replacementOrigin: "canonical-import",
          candidate,
          replacementCommandSeed: seed,
          disclosedImpact: unavailableImpact,
          currentTransition: transition as typeof transition & {
            undoDisposition: "explicitly-unavailable";
          },
          nonUndoableConfirmation:
            acknowledgement as ImportNonUndoableConfirmationAcknowledgement,
        } as const);
  return Object.freeze({
    composition,
    state,
    dependencies,
    candidate,
    request,
    acknowledgement,
    notifications: () => notificationCount,
    diagnostics,
  });
}

function preparedEcho(
  harness: Harness,
  request?: PrepareImportReplacementPublicationRequest,
): PreparedImportReplacementPublication {
  const result =
    harness.composition.interchangeOwner.prepareImportReplacementPublication(
      request ?? harness.request,
    );
  expect(result.ok).toBe(true);
  if (!result.ok) throw new Error("OWNER_TEST_PREPARE");
  return result.value;
}

function handoffFor(
  echo: PreparedImportReplacementPublication,
  retirement?: Partial<ImportReplacementHandoff["retirement"]>,
): ImportReplacementHandoff {
  return Object.freeze({
    prepared: echo,
    retirement: Object.freeze({
      requestId: REQUEST_ID,
      retiredTransportGeneration: 0,
      progressionRetired: true,
      previewRetired: true,
      noFutureAttack: true,
      ...retirement,
    } as const),
  });
}

function markerRequest(
  documentId: string,
  revision: number,
  schema: string = MARKER_SCHEMA,
): PublishCanonicalExportRevisionRequest {
  return Object.freeze({
    publication: Object.freeze({ schema, documentId, revision }),
  }) as PublishCanonicalExportRevisionRequest;
}

/** Recursively assert no state-bearing key crosses the owner boundary. */
function assertStateFree(value: unknown, path = "result"): void {
  if (typeof value !== "object" || value === null) return;
  if (Array.isArray(value)) {
    value.forEach((entry, index) => {
      assertStateFree(entry, `${path}[${String(index)}]`);
    });
    return;
  }
  for (const [key, child] of Object.entries(value)) {
    expect([
      "state",
      "currentState",
      "lastKnownState",
      "observedBefore",
    ]).not.toContain(key);
    assertStateFree(child, `${path}.${key}`);
  }
}

