describe("A0/E0 owner ports: publishImportReplacement", () => {
  test("a retained publication merges into the latest state and preserves session surfaces", () => {
    const harness = createHarness();
    const echo = preparedEcho(harness);
    // Same-revision session churn between prepare and publish: a collapsed
    // rail changes `panels`, which the merge preserves from the LATEST state
    // and the staleness recheck deliberately ignores.
    const railResult = harness.composition.controller.setRailCollapsed(
      "left",
      true,
    );
    expect(railResult.ok).toBe(true);
    // Same-value bookmark churn is not drift: deep equality governs.
    expect(harness.composition.controller.clearSelection().ok).toBe(true);
    const notificationsBeforePublish = harness.notifications();
    const result =
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      );
    expect(result).toEqual({
      ok: true,
      outcome: "committed",
      identity: {
        requestId: REQUEST_ID,
        documentId: harness.state.document.id,
        baseRevision: 0,
      },
      documentId: harness.candidate.id,
      revision: 1,
      effects: [
        {
          kind: "queue-recovery",
          revision: 1,
          requestId: null,
          reasonCode: "command:replace-document",
        },
        {
          kind: "compile-playback-plan",
          revision: 1,
          requestId: null,
          reasonCode: "command:replace-document",
        },
        {
          kind: "restore-focus",
          revision: 1,
          requestId: null,
          reasonCode: "command:replace-document",
        },
        {
          kind: "announce",
          revision: 1,
          requestId: null,
          reasonCode: "command:replace-document",
        },
      ],
      counters: {
        sectionsVisited: 1,
        measuresVisited: 1,
        eventsVisited: 0,
        stableIdsIndexed: 2,
        historyEntriesVisited: 0,
        historyBytesEstimated: STUB_ESTIMATE,
        bookmarksRepaired: 0,
        requestsCompared: 0,
        transportNotificationsCompared: 0,
        validationCalls: 1,
      },
      liveForRequest: 0,
    });
    assertStateFree(result);
    expect(harness.notifications()).toBe(notificationsBeforePublish + 1);
    const view = harness.composition.controller.getSnapshot();
    expect(view.title).toBe("Owner Bridge Candidate");
    expect(view.revision).toBe(1);
    expect(view.panels.leftRailCollapsed).toBe(true);
    // The controller's own history machinery still works over the merge:
    // a retained replacement is undoable and restores the previous chart.
    const undone = harness.composition.controller.undo();
    expect(undone.ok).toBe(true);
    expect(harness.composition.controller.getSnapshot().title).toBe(
      "Untitled Chart",
    );
  });

  test("the latest identity reader sees the publication immediately", () => {
    const harness = createHarness();
    const owner = harness.composition.interchangeOwner;
    expect(owner.readCurrentApplicationDocumentIdentity()).toEqual({
      documentId: harness.state.document.id,
      revision: 0,
    });
    const echo = preparedEcho(harness);
    owner.publishImportReplacement(handoffFor(echo));
    expect(owner.readCurrentApplicationDocumentIdentity()).toEqual({
      documentId: harness.candidate.id,
      revision: 1,
    });
  });

  test("publish consumes before returning: an exact replay refuses missing", () => {
    const harness = createHarness();
    const echo = preparedEcho(harness);
    const first = harness.composition.interchangeOwner.publishImportReplacement(
      handoffFor(echo),
    );
    expect(first).toMatchObject({ ok: true, liveForRequest: 0 });
    const replay =
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      );
    expect(replay).toMatchObject({
      ok: false,
      code: "import.replacement_preparation_missing",
      liveForRequest: 0,
    });
  });

  test("a structural lookalike is never authority and consumes the live entry", () => {
    const harness = createHarness();
    const echo = preparedEcho(harness);
    const lookalike = structuredClone(echo);
    expect(lookalike).toEqual(echo);
    const refused =
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(lookalike),
      );
    expect(refused).toMatchObject({
      ok: false,
      code: "import.replacement_preparation_missing",
    });
    // The lookalike consumed the matching live entry; the exact echo can
    // no longer publish either.
    expect(
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      ),
    ).toMatchObject({
      ok: false,
      code: "import.replacement_preparation_missing",
    });
    expect(harness.notifications()).toBe(0);
  });

  test("same-revision bookmark drift consumes and refuses stale", () => {
    const harness = createHarness();
    const echo = preparedEcho(harness);
    expect(
      harness.composition.controller.setInsertionPoint({
        kind: "document-end",
      }).ok,
    ).toBe(true);
    const refused =
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      );
    expect(refused).toMatchObject({
      ok: false,
      code: "import.replacement_preparation_stale",
      observedDocumentId: harness.state.document.id,
      observedRevision: 0,
      liveForRequest: 0,
    });
    // Consumed: a repeat is missing, not stale.
    expect(
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      ),
    ).toMatchObject({
      ok: false,
      code: "import.replacement_preparation_missing",
    });
  });

  test("retirement evidence is checked exactly and covers the latest generation", () => {
    const receipts: readonly Readonly<{
      retirement: Partial<ImportReplacementHandoff["retirement"]>;
      generation?: number;
    }>[] = [
      { retirement: { requestId: REQUEST_ID + 1 } },
      { retirement: { noFutureAttack: false as never } },
      { retirement: { retiredTransportGeneration: -1 } },
      { retirement: { retiredTransportGeneration: 4 }, generation: 5 },
    ];
    for (const { retirement, generation } of receipts) {
      const harness = createHarness(
        generation === undefined ? {} : { transportGeneration: generation },
      );
      const echo = preparedEcho(harness);
      const refused =
        harness.composition.interchangeOwner.publishImportReplacement(
          handoffFor(echo, retirement),
        );
      expect(refused).toMatchObject({
        ok: false,
        code: "import.replacement_retirement_mismatch",
        liveForRequest: 0,
      });
    }
    // The exact covering generation publishes.
    const covered = createHarness({ transportGeneration: 5 });
    const echo = preparedEcho(covered);
    expect(
      covered.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo, { retiredTransportGeneration: 5 }),
      ),
    ).toMatchObject({ ok: true, outcome: "committed" });
  });

  test("an explicitly-unavailable publication resets history and warns once", () => {
    const harness = createHarness({ disposition: "explicitly-unavailable" });
    const echo = preparedEcho(harness);
    const result =
      harness.composition.interchangeOwner.publishImportReplacement(
        handoffFor(echo),
      );
    expect(result).toMatchObject({ ok: true, outcome: "committed" });
    if (!result.ok) throw new Error("OWNER_TEST_PUBLISH");
    expect(result.effects.map((effect) => effect.kind)).toEqual([
      "queue-recovery",
      "compile-playback-plan",
      "restore-focus",
      "announce",
      "recommend-export",
    ]);
    expect(result.effects[4]).toMatchObject({ requestId: REQUEST_ID });
    const view = harness.composition.controller.getSnapshot();
    expect(view.noticeCount).toBe(1);
    expect(view.latestNotice).toMatchObject({
      code: "history.replacement_not_undoable",
    });
    // History was explicitly made unavailable: undo refuses empty.
    expect(harness.composition.controller.undo()).toMatchObject({
      ok: false,
      refusal: { code: "history.undo_empty" },
    });
  });
});

