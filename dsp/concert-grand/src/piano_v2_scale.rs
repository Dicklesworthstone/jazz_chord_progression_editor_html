fn extrapolate(
    midi: i32,
    base: ReviewedStringScaleRow,
    neighbour: ReviewedStringScaleRow,
) -> ReviewedStringScaleRow {
    let amount = (midi - base.midi) as f64 / (neighbour.midi - base.midi) as f64;
    ReviewedStringScaleRow {
        midi,
        speaking_length_m: base.speaking_length_m
            + amount * (neighbour.speaking_length_m - base.speaking_length_m),
        diameter_m: base.diameter_m + amount * (neighbour.diameter_m - base.diameter_m),
        density_kg_m3: base.density_kg_m3 + amount * (neighbour.density_kg_m3 - base.density_kg_m3),
        reported_tension_n: base.reported_tension_n
            + amount * (neighbour.reported_tension_n - base.reported_tension_n),
    }
}

/// Look up the exact reviewed C1..B7 row.  RT-0425 omits only the three
/// lowest keys and C8; those four boundary rows use the single adjacent
/// measured slope instead of an unrelated instrument's scale.
pub fn reviewed_string_scale_row(midi: i32) -> Option<ReviewedStringScaleRow> {
    match midi {
        21..=23 => Some(extrapolate(
            midi,
            REVIEWED_STRING_SCALE[0],
            REVIEWED_STRING_SCALE[1],
        )),
        24..=107 => Some(REVIEWED_STRING_SCALE[(midi - 24) as usize]),
        108 => Some(extrapolate(
            midi,
            REVIEWED_STRING_SCALE[83],
            REVIEWED_STRING_SCALE[82],
        )),
        _ => None,
    }
}
